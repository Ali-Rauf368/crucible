import { one, q } from "../db/pool.js";
import { owaspFor, OWASP } from "../eval/owasp.js";

/** Shareable Markdown report for a run (security review, release sign-off, PR comment). */
export async function runReport(runId: number): Promise<string | null> {
  const r = await one(`SELECT r.*, s.name AS suite, s.thresholds, a.name AS agent FROM runs r JOIN suites s ON s.id = r.suite_id JOIN agents a ON a.id = r.agent_id WHERE r.id = $1`, [runId]);
  if (!r) return null;
  const cases = await q(`SELECT c.*, s.category AS s_category, s.tags, s.faults, s.assertions AS specs FROM run_cases c LEFT JOIN scenarios s ON s.id = c.scenario_id WHERE c.run_id = $1 ORDER BY c.passed, c.critical DESC, c.id`, [runId]);
  const pct = (v: number | null | undefined) => (v == null || Number.isNaN(v) ? "n/a" : `${Math.round(v * 100)}%`);
  const esc = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  const sum = r.summary ?? {};
  const L: string[] = [];

  L.push(`# Crucible report: ${r.agent} on ${r.suite}`, "");
  L.push(`Run **#${r.id}** "${esc(r.label)}" · ${r.status} · trigger ${r.trigger}${r.git_sha ? ` · commit \`${String(r.git_sha).slice(0, 7)}\`` : ""} · seed \`${r.seed}\` (re-run with this seed to reproduce the exact fault schedule)`);
  L.push(`Finished ${r.finished_at ? new Date(r.finished_at).toISOString().replace("T", " ").slice(0, 16) + " UTC" : "n/a"}`, "");

  if (r.gate) {
    L.push(`## Regression gate: ${r.gate.passed ? "PASSED" : "FAILED"}`, "", `Compared with baseline run #${r.gate.baselineRunId}.`);
    for (const x of r.gate.reasons ?? []) L.push(`- ${x}`);
    L.push("");
  }

  L.push("## Scores", "", "| Overall | Accuracy | Safety | Resilience | Pass rate | p95 latency | Cost | Tokens |", "|---|---|---|---|---|---|---|---|");
  L.push(`| ${pct(r.scores?.overall)} | ${pct(r.scores?.accuracy)} | ${pct(r.scores?.safety)} | ${pct(r.scores?.resilience)} | ${pct(sum.passRate)} (${sum.passed ?? 0}/${sum.cases ?? 0}) | ${sum.latency?.p95 ?? 0} ms | $${Number(sum.costUsd ?? 0).toFixed(4)} | ${sum.tokens ?? 0} |`, "");
  L.push(`Suite threshold: overall at least ${pct(r.thresholds?.overall)}. Overall = 40% accuracy + 35% safety + 25% resilience.`, "");

  if (sum.outcomes) {
    L.push("## Outcomes", "");
    for (const [k, v] of Object.entries(sum.outcomes as Record<string, number>)) L.push(`- **${k}**: ${v}`);
    L.push("");
  }

  const faults = (sum.faults ?? {}) as Record<string, { injected: number; survived: number }>;
  if (Object.keys(faults).length) {
    L.push("## Fault survival", "", "| Fault | Cases hit | Survived |", "|---|---|---|");
    for (const [k, v] of Object.entries(faults)) L.push(`| ${k} | ${v.injected} | ${v.survived} (${pct(v.survived / v.injected)}) |`);
    L.push("");
  }

  const mapped = cases.filter((c) => c.specs).map((c) => ({ c, ids: owaspFor({ category: c.s_category, tags: c.tags ?? [], faults: c.faults ?? [], assertions: c.specs ?? [] }) }));
  const covered = OWASP.filter((o) => mapped.some((x) => x.ids.includes(o.id)));
  if (covered.length) {
    L.push("## OWASP LLM Top 10 coverage", "", "| Risk | Cases | Passed |", "|---|---|---|");
    for (const o of covered) {
      const cs = mapped.filter((x) => x.ids.includes(o.id));
      L.push(`| ${o.id} ${o.name} | ${cs.length} | ${cs.filter((x) => x.c.passed).length} |`);
    }
    L.push("");
  }

  const failed = cases.filter((c) => c.passed === false);
  L.push(`## Failing cases (${failed.length})`, "");
  if (!failed.length) L.push("None.", "");
  for (const c of failed) {
    L.push(`### ${c.critical ? "[critical] " : ""}${c.scenario_name}${r.repeats > 1 ? ` (attempt ${c.attempt})` : ""}`, "");
    L.push(`Outcome **${c.outcome}** · overall ${pct(c.scores?.overall)} · ${c.llm_calls} LLM + ${c.tool_calls} tool calls · ${c.latency_ms ?? "?"} ms`);
    const fi = (c.faults_injected ?? []) as { type: string; target: string }[];
    if (fi.length) L.push(`Faults: ${[...new Set(fi.map((f) => `${f.type}@${f.target}`))].join(", ")}`);
    for (const a of (c.assertions ?? []) as { passed: boolean; label: string; detail: string }[]) if (!a.passed) L.push(`- FAIL ${a.label}: ${esc(a.detail)}`);
    if (c.error) L.push(`- Error: \`${esc(c.error).slice(0, 300)}\``);
    if (c.judge?.reasoning) L.push(`- Judge (${c.judge.mode}): ${esc(c.judge.reasoning)}`);
    if (c.output) L.push("", "> " + esc(c.output).slice(0, 500));
    L.push("");
  }
  L.push("---", "Generated by Crucible. Trace waterfalls for every case are available in the UI.");
  return L.join("\n");
}
